from pathlib import Path
from typing import Any

import pytest

from migrateit.clients._client import SqlClient
from migrateit.cmd import cmd_export
from migrateit.models.migration import Migration
from tests.unit.cmd.conftest import _mock_client


def test_cmd_export_no_name_creates_default(client: SqlClient[Any]) -> None:
    result = cmd_export(client, name=None)

    assert result == 0
    # Default name should be <database>_backup, prefixed with 0001_
    expected_name = f"{client.database.value}_backup"
    changelog_names = [f.name for f in (client.changelog.path.parent / "migrations").iterdir()]
    assert any(expected_name in name for name in changelog_names)


def test_cmd_export_with_name(client: SqlClient[Any]) -> None:
    result = cmd_export(client, name="my_full_export")

    assert result == 0

    # Verify migration file exists
    changelog_names = [f.name for f in (client.changelog.path.parent / "migrations").iterdir()]
    files = list(Migration.migrations_dir.glob("*my_full_export*.sql"))
    assert any("my_full_export" in name for name in changelog_names)
    assert len(files) == 1

    # Verify migration content
    content = files[0].read_text()
    assert "-- Rollback migration" in content
    assert "Migration automatically generated by migrateit" in content


@pytest.mark.unit
def test_cmd_export_error(temp_dir: Path) -> None:
    client = _mock_client(temp_dir)
    client.export_database_schema.side_effect = ValueError("Error exporting database schema")  # type: ignore

    assert cmd_export(client, name="my_full_export") != 0
    assert len(list(Migration.migrations_dir.glob("*my_full_export*.sql"))) == 0
