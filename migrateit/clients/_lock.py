from __future__ import annotations

import time
from typing import Protocol, Self, override

from migrateit.clients._protocol import SqlConnectionProtocol
from migrateit.models.config import SupportedDatabase
from migrateit.reporters.logs import logger

LOCK_TIMEOUT_SECONDS = 30
LOCK_RETRY_SECONDS = 0.5


class Locker(Protocol):
    is_locked: bool = False

    def acquire(self) -> None: ...
    def release(self) -> None: ...


class _DummyLocker(Locker):
    def __init__(self, client: SqlConnectionProtocol, table_name: str) -> None:
        self._client = client
        self._table_name = table_name

    @override
    def acquire(self) -> None:
        self.is_locked = True

    @override
    def release(self) -> None:
        self.is_locked = False


class _PsqlLocker(Locker):
    def __init__(self, client: SqlConnectionProtocol, table_name: str) -> None:
        self._client = client
        self._table_name = table_name

    @override
    def acquire(self) -> None:
        key = self._compute_advisory_key(self._table_name)
        result = self._client.execute_for_one("SELECT pg_try_advisory_lock(%s)", (key,))
        if not result or not result[0]:
            raise RuntimeError(f"Could not acquire lock for {self._table_name}")
        self.is_locked = True
        logger.debug("Acquired advisory lock for table %s (key=%d)", self._table_name, key)

    @override
    def release(self) -> None:
        key = self._compute_advisory_key(self._table_name)
        self._client.execute("SELECT pg_advisory_unlock(%s)", (key,))
        self.is_locked = False
        logger.debug("Released advisory lock for table %s (key=%d)", self._table_name, key)

    @staticmethod
    def _compute_advisory_key(table_name: str) -> int:
        """Compute a deterministic advisory lock key from the table name.

        Returns a non-negative 63-bit integer suitable for PostgreSQL's
        ``pg_advisory_lock`` (which expects a signed 64-bit int).
        """
        raw = int(table_name.encode("utf-8").hex(), 16)
        return raw % (2**63)


class _MySqlLocker(Locker):
    @property
    def lock_name(self) -> str:
        return f'"{self._table_name}_lock"'

    def __init__(self, client: SqlConnectionProtocol, table_name: str) -> None:
        self._client = client
        self._table_name = table_name

    @override
    def acquire(self) -> None:
        result = self._client.execute_for_one("SELECT GET_LOCK(%s, %s)", (self.lock_name, LOCK_TIMEOUT_SECONDS))
        if result is None or result[0] == 0:
            raise RuntimeError(f"Could not acquire lock for {self._table_name}")
        self.is_locked = True
        logger.debug("Acquired MySQL lock %s for table %s", self.lock_name, self._table_name)

    @override
    def release(self) -> None:
        self._client.execute("SELECT RELEASE_LOCK(%s)", (self.lock_name,))
        self.is_locked = False
        logger.debug("Released MySQL lock %s for table %s", self.lock_name, self._table_name)


class _DBTableLocker(Locker):
    @property
    def lock_table(self) -> str:
        return f'"{self._table_name}_lock"'

    def __init__(self, client: SqlConnectionProtocol, table_name: str) -> None:
        if not table_name.isidentifier():
            raise ValueError(f"Unsafe table name: {table_name}")
        self._client = client
        self._table_name = table_name
        self._create_sql_table_for_db()

    @override
    def acquire(self) -> None:
        end_time = time.monotonic() + LOCK_TIMEOUT_SECONDS
        while time.monotonic() < end_time:
            try:
                self._client.execute(f"INSERT INTO {self.lock_table} (id) VALUES (1)")
                self._client.connection.commit()
                self.is_locked = True
                logger.debug("Acquired lock for table %s", self._table_name)
                return
            except Exception:
                if time.monotonic() >= end_time:
                    raise RuntimeError(f"Could not acquire lock for {self._table_name} within {LOCK_TIMEOUT_SECONDS}s")
            time.sleep(LOCK_RETRY_SECONDS)
        raise RuntimeError(f"Could not acquire lock for {self._table_name} within {LOCK_TIMEOUT_SECONDS}s")

    @override
    def release(self) -> None:
        self._client.execute(f"DELETE FROM {self.lock_table} WHERE id = 1")
        self._client.connection.commit()
        self.is_locked = False
        logger.debug("Released lock for table %s", self._table_name)

    def _create_sql_table_for_db(self) -> None:
        if self._client.database == SupportedDatabase.SQLITE:
            self._client.execute(f"CREATE TABLE IF NOT EXISTS {self.lock_table} (id INTEGER PRIMARY KEY);")
            self._client.connection.commit()
        if self._client.database == SupportedDatabase.ORACLE:
            import oracledb

            query = f"CREATE TABLE {self.lock_table} (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
            try:
                self._client.execute(query)
                self._client.connection.commit()
            except oracledb.DatabaseError as e:
                # ORA-00955: name is already used by an existing object
                if e.args[0].code != 955:  # pragma: no cover
                    raise
                self._client.connection.rollback()


class DatabaseLock:
    """Database-agnostic context manager for migration execution locks.

    Wraps the connection with the appropriate locking strategy for the
    connected database type. The lock is acquired on entry and released
    on exit (whether normal or via exception).
    """

    @property
    def is_locked(self) -> bool:
        return self._locker.is_locked

    def __init__(self, client: SqlConnectionProtocol, table_name: str) -> None:
        self._client = client
        self._table_name = table_name
        self._locker: Locker = self._build_locker()

    def __enter__(self) -> Self:
        self._locker.acquire()
        return self

    def __exit__(self, exc_type: type[BaseException] | None, exc_val: BaseException | None, exc_tb: object) -> None:
        self._locker.release()

    def _build_locker(self) -> Locker:
        match self._client.database:
            case SupportedDatabase.MYSQL | SupportedDatabase.MARIADB:
                return _MySqlLocker(self._client, self._table_name)
            case SupportedDatabase.POSTGRES:
                return _PsqlLocker(self._client, self._table_name)
            case SupportedDatabase.ORACLE | SupportedDatabase.SQLITE:
                return _DBTableLocker(self._client, self._table_name)
            case _:  # pragma: no cover
                return _DummyLocker(self._client, self._table_name)
